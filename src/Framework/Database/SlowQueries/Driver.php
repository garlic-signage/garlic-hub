declare(strict_types=1);

namespace App\Framework\Database\SlowQueries;

use Doctrine\DBAL\Driver as DriverInterface;
use Doctrine\DBAL\Driver\Connection as ConnectionInterface;
use Doctrine\DBAL\Driver\Middleware\AbstractDriverMiddleware;
use SensitiveParameter;

final class Driver extends AbstractDriverMiddleware
{
	public function __construct(DriverInterface $driver, private readonly SlowQueryLog $log)
	{
		parent::__construct($driver);
	}

	public function connect(#[SensitiveParameter] array $params): ConnectionInterface
	{
		return new Connection(parent::connect($params), $this->log);
	}
}
